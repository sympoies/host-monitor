export const dictionaries:{zh:Record<Key,string>;en:Record<Key,string>}={zh,en};
// Only the first preferred language decides: any zh* tag (including Simplified) maps to Traditional Chinese.
export function detectLanguage(preferred:readonly string[]|undefined):Language{return /^zh/i.test(preferred?.[0]??'')?'zh':'en';}
export function loadLanguage(store:LanguageStore,preferred:readonly string[]|undefined):Language{
 try{const saved=store.getItem(KEY);if(saved==='zh'||saved==='en')return saved;}catch{/* storage is optional */}
 return detectLanguage(preferred);
}
export function saveLanguage(store:LanguageStore,language:Language):boolean{try{store.setItem(KEY,language);return true;}catch{return false;}}
export function translate(language:Language,key:Key,params?:Record<string,string|number>):string{
 return dictionaries[language][key].replace(/\{(\w+)\}/g,(whole,name:string)=>params&&name in params?String(params[name]):whole);
}
// The locale used for dates and times; Traditional Chinese keeps the zh-TW format it always had.
export const timeLocale=(language:Language)=>language==='zh'?'zh-TW':'en-GB';
export const htmlLang=(language:Language)=>language==='zh'?'zh-Hant':'en';
